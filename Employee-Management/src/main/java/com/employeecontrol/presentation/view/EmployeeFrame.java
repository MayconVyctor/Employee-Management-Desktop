    private void loadEmployees() {
        List<Employee> employees = listEmployeesUseCase.execute();

        DefaultTableModel model =
                (DefaultTableModel) employeesTable.getModel();

        model.setRowCount(0);

        for (Employee employee : employees) {
            model.addRow(new Object[]{
                employee.getId(),
                employee.getName(),
                employee.getAdmissionDate(),
                employee.getSalary(),
                employee.isStatus() ? "Active" : "Inactive"
            });
        }
    }
